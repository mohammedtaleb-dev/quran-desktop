// Builds the lazily-loaded text data used by search and tafsir:
//   src/data/text.js      window.QURAN_TEXT = [[sura, aya, page, text], ...]  (6236 verses, imlaei spelling)
//   src/data/muyassar.js  window.MUYASSAR = { "sura:aya": "tafsir", ... }       (Tafsir Al-Muyassar)
// Sources (tools/data): quran.com API v4 verses/imlaei and tafsirs/16 (Al-Muyassar, King Fahd Complex),
// Tanzil metadata (CC BY 3.0) for page numbers.
// Usage: node tools/build-text.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const data = (f) => path.join(__dirname, 'data', f);
const ctx = {};
vm.runInNewContext(`${fs.readFileSync(data('quran-data.js'), 'utf8')};this.Q=QuranData;`, ctx);
const Q = ctx.Q;

const pageStarts = Q.Page.slice(1, 605); // [sura, aya] opening each page
const pageOf = (sura, aya) => {
  let page = 1;
  pageStarts.forEach(([s, a], i) => { if (s < sura || (s === sura && a <= aya)) page = i + 1; });
  return page;
};

const verses = JSON.parse(fs.readFileSync(data('quran-imlaei.json'), 'utf8')).verses;
if (verses.length !== 6236) throw new Error(`expected 6236 verses, got ${verses.length}`);
const text = verses.map((v) => {
  const [sura, aya] = v.verse_key.split(':').map(Number);
  return [sura, aya, pageOf(sura, aya), v.text_imlaei.trim()];
});

// Al-Muyassar explains some verses in groups; such verses share the text of the group's first verse.
const raw = JSON.parse(fs.readFileSync(data('tafsir-muyassar.json'), 'utf8'));
const clean = (html) => html.replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
const muyassar = {};
let last = '';
for (const [sura, aya] of text) {
  const key = `${sura}:${aya}`;
  if (raw[key] && clean(raw[key])) last = clean(raw[key]);
  else if (aya === 1) throw new Error(`no tafsir for ${key}`);
  muyassar[key] = last;
}

const outDir = path.join(__dirname, '..', 'src', 'data');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'text.js'), `// Generated by tools/build-text.js — do not edit.\nwindow.QURAN_TEXT = ${JSON.stringify(text)};\n`);
fs.writeFileSync(path.join(outDir, 'muyassar.js'), `// Generated by tools/build-text.js — do not edit.\nwindow.MUYASSAR = ${JSON.stringify(muyassar)};\n`);
const size = (f) => `${(fs.statSync(path.join(outDir, f)).size / 1e6).toFixed(2)} MB`;
console.log(`text.js ${size('text.js')}, muyassar.js ${size('muyassar.js')}; 2:255 on page ${pageOf(2, 255)}, 13:1 on page ${pageOf(13, 1)}`);

// Builds src/js/meta.js (surah, juz and hizb-quarter start pages) from Tanzil's metadata.
// Tanzil Quran metadata: Copyright (C) 2008-2009 Tanzil.info, Creative Commons Attribution 3.0.
// Usage: node tools/build-meta.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ctx = {};
vm.runInNewContext(`${fs.readFileSync(path.join(__dirname, 'data', 'quran-data.js'), 'utf8')};this.Q=QuranData;`, ctx);
const Q = ctx.Q;

// Q.Page[i] = [sura, aya] that opens page i; a verse lives on the last page whose opening is <= it.
const before = (a, b) => a[0] - b[0] || a[1] - b[1];
const pageOf = ([sura, aya]) => {
  let page = 1;
  for (let i = 1; i < Q.Page.length; i++) if (Q.Page[i].length && before(Q.Page[i], [sura, aya]) <= 0) page = i;
  return page;
};

const meta = {
  suras: Q.Sura.slice(1, 115).map((s, i) => ({
    name: s[4], ayas: s[1], medinan: s[7] === 'Medinan' ? 1 : 0, page: pageOf([i + 1, 1]),
  })),
  juz: Q.Juz.slice(1, 31).map(pageOf),
  quarters: Q.HizbQaurter.slice(1, 241).map(pageOf),
};

// Sanity checks against the phone app's own indexes.
const expect = { 'suras[2].page': [meta.suras[2].page, 50], 'suras[12].page': [meta.suras[12].page, 249], 'juz[11]': [meta.juz[11], 222], 'juz[15]': [meta.juz[15], 302] };
for (const [k, [got, want]] of Object.entries(expect)) if (got !== want) throw new Error(`${k} = ${got}, expected ${want}`);

const out = path.join(__dirname, '..', 'src', 'js', 'meta.js');
fs.writeFileSync(out, `// Generated by tools/build-meta.js from Tanzil metadata (CC BY 3.0) — do not edit.\nwindow.META = ${JSON.stringify(meta)};\n`);
console.log(`wrote ${out}: ${meta.suras.length} suras, ${meta.juz.length} juz, ${meta.quarters.length} quarters`);
